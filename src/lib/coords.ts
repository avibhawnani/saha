import raw from "../data/coords.json";
import type { SahaEvent } from "../data/events";

/**
 * How precisely a venue string resolved. This is the single most important
 * field on the map: rendering an area- or city-level hit as a sharp pin is a
 * lie about where the event is.
 */
export type Precision = "venue" | "area" | "city" | "none";

export interface Located {
  lat: number;
  lng: number;
  precision: Exclude<Precision, "none">;
  /** What Nominatim actually matched, for the "why is the pin here" question. */
  matched: string;
}

type Entry =
  | { lat: number; lng: number; precision: string; matched: string; query: string }
  | { precision: "none"; reason: string };

const COORDS = raw as Record<string, Entry>;

/** Generated by scripts/geocode.mjs. Null means genuinely not placeable. */
export function coordsFor(id: string): Located | null {
  const e = COORDS[id];
  if (!e || e.precision === "none" || !("lat" in e)) return null;
  return {
    lat: e.lat,
    lng: e.lng,
    precision: e.precision as Located["precision"],
    matched: e.matched,
  };
}

/** Only venue- and area-level hits get a pin. City-level is listed, not pinned. */
export function isPinnable(id: string): boolean {
  const c = coordsFor(id);
  return c !== null && (c.precision === "venue" || c.precision === "area");
}

/** Why an event is missing from the map, phrased for the reader. */
export function offMapReason(e: SahaEvent): string | null {
  if (e.placement === "remote") return "Online — no venue to place";
  const c = coordsFor(e.id);
  if (!c) return "Venue could not be located";
  if (c.precision === "city") return "Source published the city only";
  return null;
}
